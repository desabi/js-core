// Declaration and initialization
var score = 100;

// Reassignment (updating the value)
score = 150;
console.log("score:", score); // Output: 150

// Re-declaration (allowed with 'var')
var score = 200; // This will overwrite the previous declaration
console.log("score after re-declaration:", score); // Output: 200